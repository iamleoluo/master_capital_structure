"""資本結構大事記 —— 把兩年多的歷史切成幾個「公司在用不同工具」的階段。

為什麼需要這個模組:
    這個專案原本把時效性的論述寫死在常設頁面裡(例如「帳面每股在漲、實際每股在縮」),
    每次資料更新就會有一部分變成過期的錯誤敘述,而且沒有地方記錄「這段期間到底發生
    了什麼」。拆成兩層之後,常設頁只解釋機器怎麼運作,這裡記錄機器在哪段期間做了什麼。

這個模組只放「編輯內容」(標題、定性、敘述),不放任何數字 ——
每個階段的期初/期末數值、變化率、資金流全部由 web/build_data.py 在每次跑管線時
從 daily.json 與原始週資料重算。所以資料一更新,每一則的數字就跟著更新,
不會出現「文字說 +9.6% 但圖上是別的數字」這種事。

新增一則主題的流程(append-only,既有條目不要動):
    1. 把目前最後一則的 end 從 None 改成新階段的前一天
    2. 在 ERAS 尾端追加新的一則,end=None
    3. 跑 python3 web/build_data.py,數字會自己長出來
    4. tests/test_chronicle.py 會擋住日期不連續、有空隙或重疊的情況

工具代碼(TOOLS)刻意與「是否真的有動用」分開:這裡寫的是該階段的「主要手法」,
供敘事用;實際啟用狀況由管線從 atm_weekly / repurchase_weekly / weekly delta /
debt 序列判定,兩者不一致時以資料為準。

撰寫原則(重要,避免寫成新聞標題):
    分期是「哪一根槓桿在當下划算」,不是「公司又被什麼事件打到」。
    證券條款(永續、非累積、變動利率、可轉換)在發行當下就設定好了,
    遠早於壓力出現 —— 能扛住波動是結構本來就有的能力,不是臨場反應。
    每一則都要寫清楚「為什麼這個市況下該用這把工具」,而不是「發生了什麼事」。
    單一階段不是結論,判斷尺度是年;PROGRAM 的全期數字就是為了擋住這件事。
"""
